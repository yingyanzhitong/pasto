def pre_native_title(source):
    source = pre_text_submission(source)
    for path, previous, current in reversed(CHANGES):
        if current in source:
            assert source.count(current) == 1, path
            source=source.replace(current,previous,1)
    return source

def pre_native_title_bytes(path):
    path=Path(path)
    raw=path.read_bytes()
    return pre_native_title(raw.decode()).encode() if path.suffix == '.swift' else raw
