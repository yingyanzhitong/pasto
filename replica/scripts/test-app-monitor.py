#!/usr/bin/env python3
"""Launch the real app and verify its scheduled monitor against a private pasteboard."""
import argparse
import json
import pathlib
import subprocess
import tempfile
import time
import uuid


def wait_for(check, process, timeout=12):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        assert process.poll() is None, "App exited before verification completed"
        result = check()
        if result:
            return result
        time.sleep(0.1)
    raise AssertionError("Scheduled app monitor did not reach expected persisted state")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--app", type=pathlib.Path,
                        default=pathlib.Path(__file__).resolve().parents[1] / "dist/Pasto.app")
    parser.add_argument("--report", type=pathlib.Path)
    args = parser.parse_args()
    executable = args.app.resolve() / "Contents/MacOS/Pasto"
    with tempfile.TemporaryDirectory(prefix="pasto-app-test-") as temporary:
        root = pathlib.Path(temporary)
        helper = root / "pasteboard-helper.swift"
        helper.write_text('''import AppKit
let board = NSPasteboard(name: .init(CommandLine.arguments[1]))
board.clearContents()
let item = NSPasteboardItem()
item.setString(CommandLine.arguments[2], forType: .string)
if CommandLine.arguments.count > 3 {
    item.setData(Data(), forType: .init("org.nspasteboard.AutoGeneratedType"))
}
guard board.writeObjects([item]) else { exit(1) }
''')
        writer = root / "pasteboard-helper"
        subprocess.run(["xcrun", "swiftc", str(helper), "-o", str(writer)], check=True, capture_output=True)
        board = "com.pastereplica.timer-test." + str(uuid.uuid4())
        store = root / "store"
        state = store / "clipboard.json"
        with (root / "app.log").open("wb") as log:
            process = subprocess.Popen([str(executable), "--data-dir", str(store),
                                        "--pasteboard-name", board, "--no-global-hotkey"],
                                       stdout=log, stderr=log)
            try:
                wait_for(lambda: state.exists(), process)
                # Store creation precedes UI/menu setup and monitor construction. Confirm
                # actual timer activity instead of racing the monitor's initial changeCount.
                def monitor_ready():
                    if json.loads(state.read_text())["items"]:
                        return True
                    subprocess.run([str(writer), board, "Synthetic monitor warm-up " + str(uuid.uuid4())], check=True)
                    return False
                wait_for(monitor_ready, process)
                text = "Timer acceptance 中文 😀 " + str(uuid.uuid4())
                subprocess.run([str(writer), board, text], check=True)
                def captured():
                    data = json.loads(state.read_text())
                    return any(item.get("plainText") == text for item in data["items"])
                wait_for(captured, process)
                before = len(json.loads(state.read_text())["items"])
                subprocess.run([str(writer), board, "Generated content must be ignored", "generated"], check=True)
                # More than two 400ms monitor intervals; the app stays alive throughout.
                time.sleep(1.2)
                assert process.poll() is None
                assert len(json.loads(state.read_text())["items"]) == before
                result = {"passed": True, "checks": ["real AppKit bundle launched without a window",
                          "400ms timer captured private pasteboard Unicode into persistent store",
                          "running monitor ignored AutoGenerated representation"],
                          "system_clipboard_used": False, "original_app_data_used": False}
            finally:
                process.terminate()
                try:
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait()
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
