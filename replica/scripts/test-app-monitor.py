#!/usr/bin/env python3
"""Launch the real app and verify its scheduled monitor against a private pasteboard."""
import argparse
import json
import pathlib
import plistlib
import shutil
import signal
import subprocess
import tempfile
import time
import uuid


POLL_INTERVAL = 0.25
SYNC_DELAY = 0.3
WARMUP_INTERVAL = 1.0


def wait_for(check, process, timeout=12):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        assert process.poll() is None, "App exited before verification completed"
        result = check()
        if result:
            return result
        time.sleep(0.1)
    raise AssertionError("Scheduled app monitor did not reach expected persisted state")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--app", type=pathlib.Path,
                        default=pathlib.Path(__file__).resolve().parents[1] / "dist/Pasto.app")
    parser.add_argument("--report", type=pathlib.Path)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="pasto-app-test-") as temporary:
        root = pathlib.Path(temporary)
        reader_root = root / "reader"
        subprocess.run(["bash", str(pathlib.Path(__file__).with_name("build-store-reader.sh")),
                        str(reader_root)], check=True)
        reader = reader_root / "store-reader.app/Contents/MacOS/harness"
        # UserDefaults.standard follows the copied bundle identity, not the installed app.
        app = root / "Pasto.app"
        shutil.copytree(args.app.resolve(), app, symlinks=True)
        identity = "com.pastereplica.timer-test." + uuid.uuid4().hex
        info_path = app / "Contents/Info.plist"
        info = plistlib.loads(info_path.read_bytes())
        info["CFBundleIdentifier"] = identity
        info_path.write_bytes(plistlib.dumps(info))
        subprocess.run(["codesign", "--force", "--sign", "-", str(app)],
                       check=True, capture_output=True)
        executable = app / "Contents/MacOS" / info["CFBundleExecutable"]
        helper = root / "pasteboard-helper.swift"
        helper.write_text('''import AppKit
let board = NSPasteboard(name: .init(CommandLine.arguments[1]))
board.clearContents()
let item = NSPasteboardItem()
item.setString(CommandLine.arguments[2], forType: .string)
if CommandLine.arguments.count > 3 {
    item.setData(Data(), forType: .init("org.nspasteboard.AutoGeneratedType"))
}
guard board.writeObjects([item]) else { exit(1) }
''')
        writer = root / "pasteboard-helper"
        subprocess.run(["xcrun", "swiftc", str(helper), "-o", str(writer)], check=True, capture_output=True)
        board = "com.pastereplica.timer-test." + str(uuid.uuid4())
        store = root / "store"
        state = store / "clipboard.sqlite"
        def items():
            return json.loads(subprocess.check_output([str(reader), str(store)],
                                                      stderr=subprocess.PIPE, timeout=15))
        with (root / "app.log").open("wb") as log:
            process = subprocess.Popen([str(executable), "--data-dir", str(store),
                                        "--pasteboard-name", board, "--no-global-hotkey"],
                                       stdout=log, stderr=log)
            try:
                wait_for(lambda: state.exists(), process)
                # Store creation precedes UI/menu setup and monitor construction. Confirm
                # actual timer activity instead of racing the monitor's initial changeCount.
                next_warmup = 0.0
                warmup_writes = 0
                def monitor_ready():
                    nonlocal next_warmup, warmup_writes
                    if items():
                        return True
                    # A poll may start before/after the first write. Retry slowly enough
                    # for the poll plus sync debounce to complete without being reset.
                    if time.monotonic() >= next_warmup:
                        subprocess.run([str(writer), board, "Synthetic monitor warm-up " + str(uuid.uuid4())], check=True)
                        warmup_writes += 1
                        next_warmup = time.monotonic() + WARMUP_INTERVAL
                    return False
                wait_for(monitor_ready, process)
                text = "Timer acceptance 中文 😀 " + str(uuid.uuid4())
                written_at = time.monotonic()
                subprocess.run([str(writer), board, text], check=True)
                def captured():
                    return any(item.get("plainText") == text for item in items())
                wait_for(captured, process)
                capture_seconds = time.monotonic() - written_at
                assert capture_seconds >= SYNC_DELAY - 0.05, "Capture must wait for the sync debounce"
                before = len(items())
                subprocess.run([str(writer), board, "Generated content must be ignored", "generated"], check=True)
                # Allow two complete poll/debounce windows; no further writes reset them.
                time.sleep(2 * (POLL_INTERVAL + SYNC_DELAY) + 0.1)
                assert process.poll() is None
                assert len(items()) == before
                result = {"passed": True, "checks": ["real AppKit bundle launched without a window",
                          "250ms poll plus 300ms sync debounce captured private pasteboard Unicode",
                          "running monitor ignored AutoGenerated representation"],
                          "system_clipboard_used": False, "original_app_data_used": False,
                          "isolated_bundle_id": identity, "private_pasteboard": board,
                          "capture_seconds": capture_seconds, "warmup_writes": warmup_writes,
                          "poll_interval_seconds": POLL_INTERVAL, "sync_delay_seconds": SYNC_DELAY}
            except Exception as error:
                result = {"passed": False, "error": str(error),
                          "app_log": (root / "app.log").read_text(errors="replace"),
                          "isolated_bundle_id": identity, "system_clipboard_used": False}
                if args.report:
                    args.report.parent.mkdir(parents=True, exist_ok=True)
                    args.report.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
                raise
            finally:
                process.terminate()
                try:
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait()
                subprocess.run(["defaults", "delete", identity], check=False, capture_output=True)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    def exit_on_signal(number, frame):
        raise SystemExit(128 + number)
    signal.signal(signal.SIGTERM, exit_on_signal)
    main()
